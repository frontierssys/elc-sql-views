CREATE   VIEW  PV_VII_GIFT_CARD_MOVEMENT_BY_DAY AS
SELECT LEFT(pvgctl.COMPANY_CODE,2) as AFFILIATE_CODE,
    pvgctl.COMPANY_CODE ,
    pvgctl.CRE_DATET as MOVEMENT_DATE,
    'VII GIFT CARD' as GIFT_CARD_TYPE,
    CARD_NUMBER as CARD_NO,
    CASE
        WHEN EXPIRY_DATE<GETDATE() THEN 'INACTIVE'
        ELSE 'ACTIVE'
    END as GIFT_CARD_STATUS,
    ISSUANCE_DATE as ACTIVATE_DATE,
    EXPIRY_DATE as EXPIRY_DATE,
    AVAILABLE_BALANCE as BALANCE
FROM PL_VII_GIFT_CARD_TXN_LOG pvgctl
WHERE pvgctl.AVAILABLE_BALANCE IS NOT NULL;
