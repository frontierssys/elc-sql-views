    on psdbih.SALES_MEMO_ITEM_H_ID = psfdv.SALES_MEMO_ITEM_H_ID
left join PMV_SALES_LOYALTY_MOVEMENT_BY_TRANSACTION pslmbt
    on psfdv.COMPANY_CODE = pslmbt.COMPANY_CODE
    and psfdv.TRANSACTION_ID = pslmbt.POS_MEMO_NO
