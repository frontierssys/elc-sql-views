CREATE   VIEW  PMV_REPORT_STORE_INFO
--WITH SCHEMABINDING
AS
select pc.COMPANY_DESC, pc.COMPANY_CODE, pst.STORE_TYPE_CODE as STORE_TYPE_NAME, pl.LOCATION_CODE, pl.LOCATION_DESC, pl.LOCATION_NAME, pprs.MV_DT
from  dbo.PM_LOCATION pl, dbo.PM_STORE_TYPE pst, dbo.PM_COMPANY pc, dbo.PR_POS_REPORT_SUP pprs
where pl.STORE_TYPE_ID_FK  = pst.STORE_TYPE_ID and pc.COMPANY_CODE = pl.COMPANY_CODE
