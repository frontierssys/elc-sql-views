CREATE   VIEW  PV_R0064 as
SELECT
    pal.COMPANY_CODE ,
    pst.STORE_TYPE_CODE AS STORE_TYPE_NAME,
    pl.CITY_TXT AS STORE_LOCATION,
    pl.LOCATION_CODE AS STORE_ID,
    pl.LOCATION_NAME AS STORE_NAME,
    CAST (pal.AUTH_TIME as date) AS TX_DATE,
    pal.AUTH_REF_NO AS TRAN_NO,
    CAST (pal.AUTH_TIME as time) AS TRAN_TIME,
    pal.AUTH_BY as MANAGER_ID,
    ps.FIRST_NAME + ' ' + ps.LAST_NAME AS MANAGER_NAME,
    pal.AUTH_FUNCTION AS TYPE_OF_AUTHORIZATION,
    pal.AUTH_REASON + ' '+pr.REASON_DESC AS REASON_CODE
from PL_AUTHORIZATION_LOG pal
inner join PM_LOCATION pl
    on pl.COMPANY_CODE = pal.COMPANY_CODE
    and pl.LOCATION_CODE = pal.AUTH_LOC_CODE
inner join PM_STORE_TYPE pst
    on pl.STORE_TYPE_ID_FK = pst.STORE_TYPE_ID
left join PM_USER pu
    on pal.COMPANY_CODE = pu.COMPANY_CODE
    and pal.AUTH_BY = pu.USER_CODE
left join PM_STAFF ps
    on pu.STAFF_ID_FK = ps.STAFF_ID
LEFT JOIN PM_REASON pr
    ON pr.COMPANY_CODE =pal.COMPANY_CODE
    and pr.REASON_CODE =pal.AUTH_REASON
