CREATE   VIEW [dbo].[PV_R0059_BAK] AS
--PUTR.COMPANY_CODE AS DIVISION ,
--PUTR.COMPANY_CODE AS COMPANY_CODE ,
--PUTR.COMPANY_CODE AS STORE_TYPE_NAME,
--putr.CRE_DATET as TX_DATE,
--PUTR.COMPANY_CODE AS STORE_LOCATION,
--PUTR.COMPANY_CODE AS LOCATION_CODE,
--PUTR.COMPANY_CODE AS STORE_ID,
--PUTR.COMPANY_CODE AS STORE_NAME,
--PUTR.COMPANY_CODE AS REASON_CODE,
--PUTR.COMPANY_CODE AS TRANSACTION_TYPE,
--PUTR.COMPANY_CODE AS TERMINAL_ID,
--PUTR.COMPANY_CODE AS TRANSACTION_NO,
--PUTR.COMPANY_CODE AS BACKDATED_TRANSACTION_DATE,
--PUTR.COMPANY_CODE AS DATA_ENTRY_DATE,
--PUTR.COMPANY_CODE AS 	EMPLOYEE_ID_CASHIER,
--PUTR.COMPANY_CODE AS EMPLOYEE_NAME_CASHIER,
--PUTR.COMPANY_CODE AS EMPLOYEE_ID_COMMISSIONED_ASSOCIATE,
--PUTR.COMPANY_CODE AS EMPLOYEE_NAME_COMMISSIONED_ASSOCIATE,
--PUTR.COMPANY_CODE AS CONSUMER_ID,
--PUTR.COMPANY_CODE AS CONSUME_NAME,
--PUTR.COMPANY_CODE AS SKU10,
--PUTR.COMPANY_CODE AS SKU6,
--PUTR.COMPANY_CODE AS SKU4,
--PUTR.COMPANY_CODE AS PRODUCT_DESCRIPTION,
--1 AS SUGGESTED_RETAIL_PRICE,
--2 AS DISCOUNT,
--3 AS PRICE_SOLD,
--4 AS QUANTITY,
--5 AS SALES_VALUE,
--6 AS NET_SALES,
--PUTR.COMPANY_CODE AS DISCOUNT_TYPE	,
--PUTR.COMPANY_CODE AS TOTAL_SALES_VALUE,
--PUTR.COMPANY_CODE AS TOTAL_NET_SALES,
--PUTR.COMPANY_CODE AS LOYALTY_POINTS,
--PUTR.COMPANY_CODE AS TENDER
select
    psm.COMPANY_CODE ,
    psm.COMPANY_CODE as DIVISION,
    pst.STORE_TYPE_CODE as STORE_TYPE_NAME,
    CAST (psm.CRE_DATET as date) as TX_DATE,
    pl.CITY_TXT as STORE_LOCATION,
    pl.LOCATION_CODE as STORE_ID,
    pl.LOCATION_CODE as LOCATION_CODE,
    pl.LOCATION_NAME as STORE_NAME,
    pbo.REASON as REASON_CODE,
    psmt.TYPE_NAME as TRANSACTION_TYPE,
    pt.TERMINAL_NO as TERMINAL_ID,
    psm.MEMO_NO as TRANSACTION_NO,
    CAST (psm.TX_DT as date) as BACKDATED_TRANSACTION_DATE,
    CAST (psm.CRE_DATET as date) as DATA_ENTRY_DATE,
    isnull(psm.CASHIER_CODE, psm.CRE_BY ) as EMPLOYEE_ID_CASHIER,
    isnull(ps_cashier.FIRST_NAME + ' ' + ps_cashier.LAST_NAME , ps_cre.FIRST_NAME + ' ' + ps_cre.LAST_NAME ) as EMPLOYEE_NAME_CASHIER,
    ps3.STAFF_CODE as EMPLOYEE_ID_COMMISSIONED_ASSOCIATE,
    ps3.FIRST_NAME + ' '+  ps3.LAST_NAME as EMPLOYEE_NAME_COMMISSIONED_ASSOCIATE,
    psm.VIP_NO as CONSUMER_ID,
    pc.FIRSTNAME + ' ' + pc.SURNAME as CONSUME_NAME ,
    psd.SKU_10 as SKU10,
    psd.SKU_6 as SKU6,
    psd.SKU_4 as SKU4,
    psd.PRODUCT_NAME as PRODUCT_DESCRIPTION,
    abs(psmih.CUR_RETAIL_PRICE) as SUGGESTED_RETAIL_PRICE,
    psmih.CUR_RETAIL_PRICE* psmih.qty - psmih.NET_LINE_AMT as DISCOUNT,
    abs (psmih.NET_RETAIL_PRICE) as PRICE_SOLD,
    psmih.QTY as QUANTITY,
    CASE
        when psmt.TYPE_CODE = '09' then psmih.NET_LINE_AMT / psmih.QTY
        else abs(psmih.NET_LINE_AMT )/ psmih.QTY
    end  as SALES_VALUE,
    CASE
        when psmt.TYPE_CODE = '09' then psmih.NET_LINE_AMT / psmih.QTY
        else abs(psmih.NET_LINE_AMT )/ psmih.QTY
    end  as NET_SALES,
    psdh.DISC_TYPE as DISCOUNT_TYPE,
    psmih.NET_LINE_AMT as TOTAL_SALES_VALUE,
    psmih.NET_LINE_AMT as TOTAL_NET_SALES,
    pslmbt.LOYALTY_POINTS as LOYALTY_POINTS,
    pstbt.TENDERS as TENDER
from PT_SALES_MEMO psm
inner join PT_SALES_MEMO_ITEM_H psmih
    on psmih.SALES_MEMO_ID_FK = psm.SALES_MEMO_ID
inner join dbo.PT_MEMO_ITEM_STAFF_SET pmiss
    on psmih.MEMO_ITEM_STAFF_SET_ID_FK = pmiss.MEMO_ITEM_STAFF_SET_ID
inner join dbo.PT_SALES_MEMO_ITEM_STAFF psmis
    on psmis.MEMO_ITEM_STAFF_SET_ID_FK = pmiss.MEMO_ITEM_STAFF_SET_ID
inner join dbo.PM_STAFF ps3
    on ps3.COMPANY_CODE = psmis.COMPANY_CODE
    and ps3.STAFF_CODE = psmis.STAFF_NO
inner join PM_LOCATION pl
    on psm.LOCATION_ID_FK = pl.LOCATION_ID
inner join PM_TERMINAL pt
    on psm.TERMINAL_ID_FK = pt.TERMINAL_ID
inner join PM_STORE_TYPE pst
    on pl.STORE_TYPE_ID_FK = pst.STORE_TYPE_ID
inner join PM_SALES_MEMO_TYPE psmt
    on psm.SALES_MEMO_TYPE_ID_FK = psmt.SALES_MEMO_TYPE_ID
inner join PM_BACKDATE_OTP pbo
    on psm.TXN_MODE_ID = pbo.BACKDATE_OTP_ID
left join PV_SALES_TENDER_BY_TRANSACTION pstbt
    on pstbt.SALES_MEMO_ID = psm.SALES_MEMO_ID
left join PMV_SALES_LOYALTY_MOVEMENT_BY_TRANSACTION pslmbt
    on pslmbt.COMPANY_CODE = psm.COMPANY_CODE
    and pslmbt.POS_MEMO_NO = psm.POS_MEMO_NO
left join PT_SALES_DISCOUNT_D psdd
    on psdd.SALES_MEMO_ITEM_H_ID_FK = psmih.SALES_MEMO_ITEM_H_ID
left join PT_SALES_DISCOUNT_H psdh
    on psdd.SALES_DISCOUNT_H_ID_FK = psdh.SALES_DISCOUNT_H_ID
left join PV_SKU_DETAIL psd
    on psmih.COMPANY_CODE = psd.COMPANY_CODE
    and psmih.SKU = psd.SKU_10
left join PM_VIP pv
    on pv.COMPANY_CODE = psm.COMPANY_CODE
    and pv.VIP_NO = psm.VIP_NO
left join PM_CUSTOMER pc
    on pv.CUSTOMER_ID_FK = pc.CUSTOMER_ID
left join PM_USER pu_cashier
    on pu_cashier.COMPANY_CODE = psm.COMPANY_CODE
    and pu_cashier.USER_CODE = psm.CASHIER_CODE
left join PM_STAFF ps_cashier
    on pu_cashier.STAFF_ID_FK = ps_cashier.STAFF_ID
left join PM_USER pu_cre
    on psm.COMPANY_CODE = pu_cre.COMPANY_CODE
    and psm.CRE_BY = pu_cre.USER_CODE
left join PM_STAFF ps_cre
    on ps_cre.STAFF_ID = pu_cre.STAFF_ID_FK
where psm.TXN_MODE = 'BACKDATE'
