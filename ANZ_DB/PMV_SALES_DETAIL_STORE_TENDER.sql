CREATE VIEW [DBO].[PMV_SALES_DETAIL_STORE_TENDER]
--WITH SCHEMABINDING
AS
SELECT
    PSM.TX_DATE AS TX_DATE,
    CAST(CAST(PSM.TX_DT AS TIME) AS VARCHAR(8)) AS TX_TIME,
    PC2.COMPANY_CODE AS COMPANY_CODE,
    PC2.COMPANY_DESC AS COMPANY_DESC,
    PST.STORE_TYPE_CODE AS STORE_TYPE_CODE,
    PST.STORE_TYPE_CODE AS STORE_TYPE_NAME,
    PL.LOCATION_DESC,
    PL.CITY_TXT AS STORE_LOCATION,
    PL.LOCATION_CODE AS STORE_ID,
    PL.LOCATION_CODE AS LOCATION_CODE,
    PL.LOCATION_DESC AS STORE_NAME,
    PSM.MEMO_NO AS TRANSACTION_ID,
    PSM.TX_DT AS TRANSACTION_TIME,
    PT2.TENDER_CODE AS TENDER_CODE,
    CASE
        WHEN PT2.TENDER_NAME = 'CASH' THEN PT2.TENDER_NAME + ' - ' + PC.CCY_CODE
        ELSE PT2.TENDER_NAME
    END AS TENDER_NAME,
    SUM(PSMP.AMOUNT) AS AMOUNT,
    PSM.POS_MEMO_NO AS POS_TRANSACTION_ID,
    CASE
        WHEN RIGHT(PL.COUNTRY_ID_FK,
            3)= 'MAC' THEN 'MO'
        WHEN RIGHT(PL.COUNTRY_ID_FK,
            3)= 'HKG' THEN 'HK'
        ELSE LEFT(PL.COMPANY_CODE,
            2)
    END AS ENTITY,
    PSM.CASHIER_CODE AS EMPLOYEE_ID,
    PU.NAME AS EMPLOYEE_NAME,
    POMBT.ORIG_MEMO_NO AS ORIGINAL_TRANSACTION_ID
FROM
    DBO.PT_SALES_MEMO_PAYMENT PSMP
INNER JOIN DBO.PT_SALES_MEMO PSM
    ON
    PSMP.SALES_MEMO_ID_FK = PSM.SALES_MEMO_ID
INNER JOIN DBO.PM_COMPANY PC2
    ON
    PC2.COMPANY_CODE = PSMP.COMPANY_CODE
INNER JOIN DBO.PM_TERMINAL PT
    ON
    PSM.TERMINAL_ID_FK = PT.TERMINAL_ID
INNER JOIN DBO.PM_LOCATION PL
    ON
    PT.LOCATION_ID_FK = PL.LOCATION_ID
INNER JOIN DBO.PM_STORE_TYPE PST
    ON
    PL.STORE_TYPE_ID_FK = PST.STORE_TYPE_ID
LEFT JOIN DBO.PM_TENDER PT2
    ON
    PSMP.TENDER_ID_FK = PT2.TENDER_ID
LEFT JOIN DBO.PM_CURRENCY PC
    ON
    PT2.CURRENCY_ID_FK = PC.CURRENCY_ID
LEFT JOIN PM_USER PU ON
    PU.COMPANY_CODE = PSM.COMPANY_CODE
    AND PU.USER_CODE = PSM.CASHIER_CODE
INNER JOIN DBO.PR_POS_REPORT_SUP PPRS
    ON
    1 = 1
LEFT JOIN PV_ORIG_MEMO_BY_TRANSACTION POMBT ON
    POMBT.SALES_MEMO_ID = PSM.SALES_MEMO_ID
    AND POMBT.ORIG_MEMO_NO IS NOT NULL
WHERE
    PSM.TX_DT < PPRS.MV_DT
GROUP BY
    PSM.TX_DATE ,
    CAST(CAST(PSM.TX_DT AS TIME) AS VARCHAR(8)) ,
    PC2.COMPANY_CODE ,
    PC2.COMPANY_DESC ,
    PST.STORE_TYPE_CODE ,
    PST.STORE_TYPE_NAME ,
    PL.LOCATION_DESC,
    PL.CITY_TXT ,
    PL.LOCATION_CODE ,
    PL.LOCATION_DESC ,
    PSM.MEMO_NO,
    PSM.TX_DT,
    PT2.TENDER_CODE,
    CASE
        WHEN RIGHT(PL.COUNTRY_ID_FK,
            3)= 'MAC' THEN 'MO'
        WHEN RIGHT(PL.COUNTRY_ID_FK,
            3)= 'HKG' THEN 'HK'
        ELSE LEFT(PL.COMPANY_CODE,
            2)
    END ,
    --PT2.TENDER_NAME,
    CASE
        WHEN PT2.TENDER_NAME = 'CASH' THEN PT2.TENDER_NAME + ' - ' + PC.CCY_CODE
        ELSE PT2.TENDER_NAME
    END,
    PSM.POS_MEMO_NO,
    PSM.CASHIER_CODE ,
    PU.NAME,
    POMBT.ORIG_MEMO_NO;
