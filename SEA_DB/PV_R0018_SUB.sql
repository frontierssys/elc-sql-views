--COMPANY_CODE as INVENTORY_BUCKET,
--COMPANY_CODE as TX_DATE,
--COMPANY_CODE as OPENING_QUANTITY,
--COMPANY_CODE as RTW_QUANTITY,
--COMPANY_CODE as ADJUSTMENT_QUANTITY,
--COMPANY_CODE as CLOSING_QUANTITY,
--COMPANY_CODE as OPENING_$_VALUE,
--COMPANY_CODE as CLOSING_$_VALUE,
--COMPANY_CODE as UPC,
--COMPANY_CODE as SUB_BRAND,
--COMPANY_CODE as MAJOR_CATEGORY,
--COMPANY_CODE as APPLICATION,
--COMPANY_CODE as CATEGORY,
--COMPANY_CODE as SUB_CATEGORY,
--COMPANY_CODE as INVENTORY_HIERARCHY,
--COMPANY_CODE as L1,
--COMPANY_CODE as L2,
--COMPANY_CODE as L3,
--COMPANY_CODE as L4,
--COMPANY_CODE as L5,
-- REDO END
    COMPANY_CODE ,
    LOCATION_ID ,
    MOVEMENT_DT ,
    SKU,
    BUCKET ,
    isnull(sum([SALES]), 0) as SALES_QTY,
    isnull(sum([TRANSFER_OUT]), 0) as TRANSFER_OUT_QTY,
    isnull(sum([TRANSFER_IN]), 0) as TRANSFER_IN_QTY,
    isnull(sum([RETURN]), 0) as RETURN_QTY,
    isnull(sum([ASN]), 0) as RECEIVE_QTY,
    isnull(sum([ADJUSTMENT]), 0) as ADJUSTMENT_QTY,
    isnull(sum([RTW]), 0) as RTW_QTY
    --[BUCKET_TRANSFER]
from
    (
        Select pimbd.COMPANY_CODE , pimbd.LOCATION_ID , pimbd.MOVEMENT_DT , pimbd.BUCKET ,pimbd.SKU, pimbd.ORDER_NUMBER , pimbd.TRANS_TYPE , pimbd.MOVEMENT_QTY
        from PMV_INVENTORY_MOVEMENT_BY_DAY pimbd
    ) d
PIVOT
    (
        SUM(MOVEMENT_QTY)
        for TRANS_TYPE in ([SALES], [TRANSFER_OUT], [TRANSFER_IN], [RETURN], [ASN], [ADJUSTMENT], [RTW])
    ) piv
group by
    COMPANY_CODE ,
    LOCATION_ID ,
    MOVEMENT_DT ,
    SKU,
    BUCKET
