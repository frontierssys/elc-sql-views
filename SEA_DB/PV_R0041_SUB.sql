CREATE   VIEW PV_R0041_SUB as
select
    pgc.COMPANY_CODE,
    pgc.GC_SEQ_NO,
    pgc.CARD_NO,
    pgc.GIFT_CARD_STATUS,
    pgc.ACTIVATE_DATE,
    pgc.CRE_DATET,
    pgc.FACE_VALUE,
    SUM(pgcl.MOVEMENT_AMT) over(
        PARTITION BY pgc.COMPANY_CODE, pgc.CARD_NO
        ORDER BY pgc.COMPANY_CODE, pgc.CARD_NO, pgcl.MOVEMENT_DT ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW ) as BALANCE,
    pgc.EXPIRY_DATE,
    pl.LOCATION_CODE AS GIFT_CARD_LOG_LOCATION_CODE,
    pst.STORE_TYPE_CODE AS GIFT_CARD_LOG_STORE_TYPE_NAME,
    pl2.LOCATION_CODE AS GIFT_CARD_MASTER_LOCATION_CODE,
    pst2.STORE_TYPE_CODE AS GIFT_CARD_MASTER_STORE_TYPE_NAME,
    pgcl.MOVEMENT_DT AS TX_DATE,
    pgcl.ORDER_NUMBER,
    ROW_NUMBER() OVER (
        PARTITION BY pgc.COMPANY_CODE, pgc.CARD_NO
        ORDER BY pgc.COMPANY_CODE, pgc.CARD_NO, pgcl.MOVEMENT_DT) row_num,
    count(*) OVER (
        PARTITION BY pgc.COMPANY_CODE, pgc.CARD_NO) cnt
from PM_GIFT_CARD pgc
left join PL_GIFT_CARD_LOG pgcl on pgc.COMPANY_CODE = pgcl.COMPANY_CODE and pgc.CARD_NO = pgcl.CARD_NO
left JOIN PM_LOCATION pl ON pgcl.COMPANY_CODE = pl.COMPANY_CODE AND pgcl.LOCATION_CODE = pl.LOCATION_CODE
left JOIN PM_STORE_TYPE pst ON pl.STORE_TYPE_ID_FK = pst.STORE_TYPE_ID
left JOIN PM_LOCATION pl2 ON pgc.COMPANY_CODE = pl2.COMPANY_CODE AND pgc.LOCATION_CODE = pl2.LOCATION_CODE
left JOIN PM_STORE_TYPE pst2 ON pl2.STORE_TYPE_ID_FK = pst2.STORE_TYPE_ID
WHERE pgc.GC_SEQ_NO IS NOT NULL
