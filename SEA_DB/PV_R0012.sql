CREATE   VIEW [dbo].[PV_R0012] AS
SELECT CUSTOMER_TYPE,COMPANY_CODE,COMPANY_DESC,
    LOCATION_CODE ,
    LOCATION_DESC ,
    LOCATION_NAME ,
    ADDRESS,
    STORE_TYPE_NAME,
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    IS_REVENUE_ITEM,
    TX_DATE,
    SUM(TARGET_AMOUNT) as TARGET_AMOUNT,
    SALE_OR_RETURN,
    DEMOGRAPHIC,
    SUM(SALES_GROSS_AMT) as SALES_GROSS_AMT,
    SUM(SALES_NET_AMT) as SALES_NET_AMT,
    SUM(QTY) as QTY,
    SUM(MEMO_COUNT) as MEMO_COUNT,
    SUM(DISCOUNT) as DISCOUNT
from PMV_SALES_STORE_STAFF_DEMOGRAPHIC_ALL prsp
--where prsp.IS_REVENUE_ITEM='Y'
--and LOCATION_CODE ='HKCM0015' and TX_DATE >='2021-02-01' and TX_DATE <='2021-02-28'
group BY
    CUSTOMER_TYPE,COMPANY_CODE,COMPANY_DESC,
    LOCATION_CODE ,
    LOCATION_DESC ,
    LOCATION_NAME ,
    ADDRESS,
    STORE_TYPE_NAME,
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    IS_REVENUE_ITEM,
    TX_DATE,
    SALE_OR_RETURN,
    DEMOGRAPHIC
