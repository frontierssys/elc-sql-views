CREATE  VIEW [dbo].[PV_R8804_DAILY] AS
SELECT
    C.COMPANY_CODE,
    C.POS_URL,
    C.CLIENT_URL,
    C.BRAND_CODE,
    C.LOCATION_CODE,
    C.LOCATION_DESC,
    C.F_TX_DT,
    C.WEEK_NAME,
    C.TG_AMT,
    C.NET_LINE_AMT,
    C.DAILY_COMP_PCT,
    C.CUMULATIVE_COMP_PCT,
    Convert(decimal(18,2),
        (
            CASE
                WHEN isnull(L.NET_LINE_AMT,0)=0 and C.NET_LINE_AMT>0 THEN 1
                WHEN isnull(L.NET_LINE_AMT,0)=0 and C.NET_LINE_AMT<=0 THEN 0
                ELSE (C.NET_LINE_AMT-L.NET_LINE_AMT)/L.NET_LINE_AMT
            END ) *100) CUMULATIVE_ADD,
    C.PERSON_COUNT,
    C.SAL_QTY,
    C.CUST_UNIT_PRICE,
    C.CUST_QTY,
    CONVERT(varchar(100), DATEADD(YEAR,-1, C.F_TX_DT), 111)  L_F_TX_DT,
    datename(weekday, CONVERT(varchar(100), CONVERT(varchar(100), DATEADD(YEAR,-1, C.F_TX_DT), 111), 111)) L_WEEK_NAME,
    isnull(L.TG_AMT,0.00) L_TG_AMT,
    isnull(L.NET_LINE_AMT,0.00) L_NET_LINE_AMT,
    isnull(L.DAILY_COMP_PCT,0.00) L_DAILY_COMP_PCT,
    isnull(L.CUMULATIVE_COMP_PCT,0.00) L_CUMULATIVE_COMP_PCT,
    isnull(L.CUMULATIVE_ADD,0.00) L_CUMULATIVE_ADD,
    isnull(L.PERSON_COUNT,0.00) L_PERSON_COUNT,
    isnull(L.SAL_QTY,0.00) L_SAL_QTY,
    isnull(L.CUST_UNIT_PRICE,0.00) L_CUST_UNIT_PRICE,
    isnull(L.CUST_QTY,0.00) L_CUST_QTY,
    C.CUMULATIVE_TG_AMT,
    C.CUMULATIVE_LINE_AMT,
    isnull(L.CUMULATIVE_TG_AMT,0.00) L_CUMULATIVE_TG_AMT,
    isnull(L.CUMULATIVE_LINE_AMT,0.00) L_CUMULATIVE_LINE_AMT
FROM
    PV_R8804_BASE C
LEFT JOIN PV_R8804_BASE L
    ON C.BRAND_CODE=L.BRAND_CODE  AND
    C.LOCATION_CODE=L.LOCATION_CODE AND
    CONVERT(varchar(100), DATEADD(YEAR,-1,C.F_TX_DT), 111) = L.F_TX_DT
