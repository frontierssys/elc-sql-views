CREATE VIEW PV_R0036B as
Select
    LEFT(p1.COMPANY_CODE,2) as AFFILIATE_CODE,
    p1.COMPANY_CODE,
    p1.VIP_GRADE_CODE,
    ISNULL(p1.MOVEMENT_DT,'2000-01-01') as MOVEMENT_DT,
    ISNULL(SUM(d.CUST_COUNT),0) as AS_OF_BEGIN_CUST_COUNT ,
    p1.NEW_CUST,
    p1.EXPIRED_CUST *-1 as EXPIRED_CUST,
    ISNULL(SUM(d.CUST_COUNT),0) + p1.NEW_CUST+p1.EXPIRED_CUST as AS_OF_CLOSE_CUST_COUNT
from PMV_R0036B_SUB p1
left join (
    Select COMPANY_CODE, VIP_GRADE_CODE, ISNULL(MOVEMENT_DT,'2000-01-01') as MOVEMENT_DT, SUM(CONSUMER_COUNT) as CUST_COUNT
    from PV_MEMBERSHIP_BY_TIER_MOVEMENT_BY_DAY
    group by COMPANY_CODE, VIP_GRADE_CODE, MOVEMENT_DT) d
    ON d.COMPANY_CODE=p1.COMPANY_CODE and d.VIP_GRADE_CODE=p1.VIP_GRADE_CODE
    and d.MOVEMENT_DT <p1.MOVEMENT_DT
    --where p1.VIP_GRADE_CODE ='Prospect' and p1.MOVEMENT_DT <='2021-10-22 00:00:00.000'
group by p1.COMPANY_CODE, p1.VIP_GRADE_CODE, ISNULL(p1.MOVEMENT_DT,'2000-01-01'),p1.NEW_CUST,p1.EXPIRED_CUST
