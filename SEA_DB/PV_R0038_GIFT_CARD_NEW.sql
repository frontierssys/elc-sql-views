CREATE   VIEW PV_R0038_GIFT_CARD_NEW as
SELECT prgc.COMPANY_CODE ,
    prgc.LOCATION_CODE,
    prgc.DIVISION,
    prgc.ORDER_TYPE,
    prgc.STORE_TYPE_NAME,
    prgc.STORE_LOCATION,
    prgc.STORE_ID,
    prgc.STORE_NAME,
    prgc.LIABILITY_TYPE,
    prgc.LIABILITY_ID,
    prgc.LIABILITY_DESCRIPTION,
    prgc.TRAN_TYPE,
    prgc.STATUS,
    prgc.TRANSACTION_NUMBER,
    prgc.TX_DATE,
    prgc.TRANSACTION_TIME,
    prgc.BA_ID,
    prgc.BA_NAME,
    prgc.CUSTOMER_ID,
    prgc.CUSTOMER_NAME,
    pv.MATERIAL_CODE_10  as SKU10,
    pv.MATERIAL_CODE_6  as SKU6 ,
    pv.MATERIAL_CODE_4  as SKU4 ,
    pv.PRODUCT_NAME  as PRODUCT_DESCRIPTION,
    pv.QUANTITY  as QUANTITY,
    pv.NET_SALES as SALES_AMOUNT,
    prgc.REMAINING_BALANCE,
    prgc.ORIGINAL_PURCHASE_DATE,
    prgc.DAYS_SINCE_POURCHASE_DATE,
    prgc.EXPIRATION_DATE,
    prgc.EXPIRED
FROM PV_R0038_GIFT_CARD prgc
LEFT JOIN PV_R0038_PV_R0016 pv ON pv.COMPANY_CODE = prgc.COMPANY_CODE AND pv.TRANSACTION_ID=prgc.TRANSACTION_NUMBER
