CREATE   view PV_MEMBERSHIP_BY_TIER_MOVEMENT_BY_DAY as
select pv.COMPANY_CODE ,pvg.VIP_GRADE_CODE ,pvt.START_DATE as MOVEMENT_DT ,'NEW' as MOVEMENT_TYPE ,COUNT(DISTINCT pv.VIP_NO) as CONSUMER_COUNT
from PM_VIP pv
inner join PM_VIP_TYPE pvt on pvt.VIP_TYPE_ID =pv.VIP_TYPE_ID_FK and pvt.COMPANY_CODE =pv.COMPANY_CODE
inner join PM_VIP_GRADE pvg on pvg.VIP_GRADE_ID =pvt.VIP_GRADE_ID_FK
--where pv.COMPANY_CODE ='TWEL'
group by pv.COMPANY_CODE ,pvg.VIP_GRADE_CODE ,pvt.START_DATE
UNION ALL
select pv.COMPANY_CODE ,pvg.VIP_GRADE_CODE ,pvt.EXPIRY_DAY as MOVEMENT_DT ,'EXPIRED' as MOVEMENT_TYPE ,COUNT(DISTINCT pv.VIP_NO)*-1 as CONSUMER_COUNT
from PM_VIP pv
inner join PM_VIP_TYPE pvt on pvt.VIP_TYPE_ID =pv.VIP_TYPE_ID_FK and pvt.COMPANY_CODE =pv.COMPANY_CODE
inner join PM_VIP_GRADE pvg on pvg.VIP_GRADE_ID =pvt.VIP_GRADE_ID_FK
where --pv.COMPANY_CODE ='TWEL' and
    pvt.EXPIRY_DAY is not null
group by pv.COMPANY_CODE ,pvg.VIP_GRADE_CODE,pvt.EXPIRY_DAY
