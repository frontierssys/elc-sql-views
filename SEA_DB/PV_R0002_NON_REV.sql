CREATE   VIEW PV_R0002_NON_REV AS
SELECT
    COMPANY_CODE as 'COMPANY_CODE',
    location_code as 'LOCATION_CODE',
    TX_DATE as 'TX_DATE',
    TYPE_CODE as 'TYPE_CODE' ,
    NON_REVENUE_PRODUCT_TYPE as 'NON_REVENUE_PRODUCT_TYPE',
    SALES_GROSS_AMT as 'SALES_GROSS_AMT',
    SALES_NET_AMT as 'SALES_NET_AMT',
    MARKDOWN as 'MARKDOWN',
    QTY as 'QTY',
    MEMO_COUNT as 'MEMO_COUNT',
    TERMINAL_NO as 'TERMINAL_NO'
FROM
    PV_R0002_NON_REV_SUB
WHERE
    IS_REVENUE_ITEM = 'N'
