CREATE     VIEW PV_R0022_ASN as
select
    'ASN' as INVENTORY_TYPE ,
    pstin.STORE_TYPE_CODE as STORE_TYPE_NAME,
    pc.COMPANY_CODE as COMPANY_CODE ,
    pc.COMPANY_DESC as COMPANY_DESC,
    iarh.ASN_RECEIVED_NO as DOCUMENT_ID,
    iad.TARGET_BALANCE ,
    iad.SKU_CODE as SKU_10,
    Left(iad.SKU_CODE,6) as SKU_6,
    Left(iad.SKU_CODE,4) as SKU_4,
    psd.PRODUCT_NAME as PRODUCT_NAME,
    psd.UPC as UPC,
    psd.PRODUCT_BRAND as SUB_BRAND,
    psd.MAJOR_CATEGORY + ' ' + psd.MAJOR_CATEGORY_DESC as MAJOR_CATEGORY,
    psd.MAJOR_CATEGORY as MAJOR_CATEGORY_CODE,
    psd.APPLICATION + ' ' + psd.APPLICATION_DESC as APPLICATION,
    psd.APPLICATION as APPLICATION_CODE,
    psd.CATEGORY +' ' + psd.CATEGORY_DESC as CATEGORY,
    psd.CATEGORY as CATEGORY_CODE,
    psd.SUB_CATEGORY + ' ' + psd.SUB_CATEGORY_DESC as SUB_CATEGORY,
    psd.SUB_CATEGORY as SUB_CATEGORY_CODE,
    psd.INVENTORY_HIER as 'INVENTORY_HIER',
    iad.TOTAL_QTY as EXPECTED_QTY,
    iad.TOTAL_QTY * psd.RETAIL_PRICE  as EXPECTED_VALUE,
    iard.TOTAL_QTY as RECEIVED_QTY,
    iard.TOTAL_QTY * psd.RETAIL_PRICE as RECEIVED_VALUE,
    iard.TOTAL_QTY - iad.TOTAL_QTY as VARIANCE_QTY,
    (iard.TOTAL_QTY - iad.TOTAL_QTY) * psd.RETAIL_PRICE as VARIANCE_VALUE,
    CASE
        WHEN iard.TOTAL_QTY = iad.TOTAL_QTY then 'N'
        WHEN iad.TOTAL_QTY is null or iad.TOTAL_QTY is null then null
        else 'Y'
    end as VARIANCE_PROMPT,
    'Warehouse' as SHIPPING_STORE_CODE ,
    'Warehouse' as SHIPPING_STORE_NAME,
    '' as SHIPPING_STORE_LOCATION,
    '' as SHIPPING_STORE_TYPE,
    iah.SAP_SHIP_TO_ACCOUNT as RECEIVING_STORE_CODE ,
    plin.LOCATION_DESC as RECEIVING_STORE_NAME,
    plin.CITY_TXT as RECEIVING_STORE_LOCATION,
    pstin.STORE_TYPE_CODE as RECEIVING_STORE_TYPE,
    --iah.CRE_DATET as CREATE_DATE,
    FORMAT(iah.CRE_DATET,'yyyy-MM-dd hh:mm:ss') as CREATE_DATE,
    CONVERT(varchar(10), iah.CRE_DATET, 126) as TX_DT,
    null as SHIPPING_DATE,
    iad.TARGET_BALANCE as REASON_CODE,
    --FORMAT(iarh.RECEIVED_DATE,'yyyy-MM-dd hh:mm:ss') as RECEIVE_DATE,
    CASE
        when iarh.STATUS = 'CONFIRM' then FORMAT(iarh.RECEIVED_DATE,'yyyy-MM-dd hh:mm:ss')
        ELSE NULL
    END as RECEIVE_DATE,
    null as APPROVAL_DATE,
    COALESCE (iarh.UPDATE_BY ,iarh.CRE_BY) as RECEIVER_ID,
    CASE
        WHEN iarh.UPDATE_BY is null then ps2.FIRST_NAME +' '+ left(ps2.LAST_NAME,1) + '.'
        else ps.FIRST_NAME +' '+ left(ps.LAST_NAME,1)
    end as RECEIVER_NAME,
    psd.RETAIL_PRICE as SUGGESTED_RETAIL_PRICE,
    'ASN RECEIVE' as ORDER_TYPE,
    iah.PO_NO as PO_REF_NO,   -----------------
    iah.DELIVERY_NO as DELIVERY_NOTE_NO,
    CASE
        when iarh.STATUS = 'CONFIRM' then 'CLOSED'
        else 'IN PROGRESS'
    end as STATUS,
    null as STOCK_TRANSFER_DURATION_DAY,
    CASE
        WHEN RIGHT(plin.COUNTRY_ID_FK,3)='MAC' THEN 'MO'
        WHEN RIGHT(plin.COUNTRY_ID_FK,3)='HKG' THEN 'HK'
        ELSE LEFT(plin.COMPANY_CODE,2)
    END as ENTITY,
    psa.DEFAULT_UOM_CODE as UOM
from IT_ASN_H iah
INNER JOIN IT_ASN_D iad ON iad.ASN_H_ID_FK= iah.ASN_H_ID
LEFT JOIN IT_ASN_RECEIVED_H iarh on iarh.ASN_H_ID_FK = iah.ASN_H_ID
LEFT JOIN IT_ASN_RECEIVED_D iard on iard.ASN_RECEIVED_H_ID_FK = iarh.ASN_RECEIVED_H_ID and iad.SKU_CODE =iard.SKU_CODE
INNER JOIN PM_COMPANY pc on iah.COMPANY_CODE = pc.COMPANY_CODE
INNER JOIN PM_LOCATION plin on iah.COMPANY_CODE = plin.COMPANY_CODE and iah.SAP_SHIP_TO_ACCOUNT = plin.LOCATION_CODE
LEFT JOIN PM_STORE_TYPE pstin on plin.COMPANY_CODE = pstin.COMPANY_CODE and plin.STORE_TYPE_ID_FK = pstin.STORE_TYPE_ID
LEFT JOIN PM_USER pu on pu.USER_CODE = iarh.UPDATE_BY and pu.COMPANY_CODE = iah.COMPANY_CODE
LEFT JOIN PM_STAFF ps on ps.STAFF_ID = pu.STAFF_ID_FK
LEFT JOIN PM_USER pu2 on pu2.USER_CODE = iarh.CRE_BY and pu2.COMPANY_CODE = iah.COMPANY_CODE
LEFT JOIN PM_STAFF ps2 on ps2.STAFF_ID = pu2.STAFF_ID_FK
LEFT join PV_SKU_DETAIL psd on iad.SKU_CODE = psd.SKU_10 and iad.COMPANY_CODE = psd.COMPANY_CODE
LEFT join PM_SKU ps21 on iad.COMPANY_CODE = ps21.COMPANY_CODE and iad.SKU_CODE = ps21.SKU_CODE
LEFT join PM_SKU_ATTR psa on iad.COMPANY_CODE = psa.COMPANY_CODE and psa.SKU_ATTR_ID  = ps21.SKU_ATTR_ID_FK
--where iah.ASN_NO ='2098372171';



