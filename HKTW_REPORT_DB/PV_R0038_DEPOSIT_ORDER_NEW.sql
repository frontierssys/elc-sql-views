CREATE   VIEW PV_R0038_DEPOSIT_ORDER_NEW as
SELECT prdo.COMPANY_CODE ,
    prdo.LOCATION_CODE,
    prdo.DIVISION,
    prdo.ORDER_TYPE,
    prdo.STORE_TYPE_NAME,
    prdo.STORE_LOCATION,
    prdo.STORE_ID,
    prdo.STORE_NAME,
    prdo.LIABILITY_TYPE,
    prdo.LIABILITY_ID,
    prdo.LIABILITY_DESCRIPTION,
    prdo.TRAN_TYPE,
    prdo.STATUS,
    prdo.TRANSACTION_NUMBER,
    prdo.TX_DATE,
    prdo.TRANSACTION_TIME,
    prdo.BA_ID,
    prdo.BA_NAME,
    prdo.CUSTOMER_ID,
    prdo.CUSTOMER_NAME,
    pv.MATERIAL_CODE_10  as SKU10,
    pv.MATERIAL_CODE_6  as SKU6 ,
    pv.MATERIAL_CODE_4  as SKU4 ,
    pv.PRODUCT_NAME  as PRODUCT_DESCRIPTION,
    pv.QUANTITY  as QUANTITY,
    CASE
        WHEN TRAN_TYPE ='Deposit PickUp' THEN pv.NET_SALES*-1
        ELSE pv.NET_SALES
    END as SALES_AMOUNT,
    CASE
        WHEN TRAN_TYPE ='Deposit PickUp' THEN 0
        ELSE pv.NET_SALES
    END as REMAINING_BALANCE,
    prdo.ORIGINAL_PURCHASE_DATE,
    prdo.DAYS_SINCE_POURCHASE_DATE,
    prdo.EXPIRATION_DATE,
    prdo.EXPIRED
FROM PV_R0038_DEPOSIT_ORDER prdo
LEFT JOIN PV_R0016 pv ON pv.TRANSACTION_ID=prdo.TRANSACTION_NUMBER;
