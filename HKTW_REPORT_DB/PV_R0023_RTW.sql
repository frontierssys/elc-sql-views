-- dbo.PV_R0023_RTW source

CREATE     view PV_R0023_RTW as
select
    'RETURN TO WAREHOUSE' as INVENTORY_TYPE ,
    pst.STORE_TYPE_CODE as STORE_TYPE_NAME,
    pc.COMPANY_CODE as COMPANY_CODE ,
    pc.COMPANY_DESC as COMPANY_DESC,
    irtwh.RTW_NO as DOCUMENT_ID,
    irtwd.SKU_CODE as SKU_10,
    LEFT(irtwd.SKU_CODE, 6) as SKU_6,
    LEFT(irtwd.SKU_CODE, 4) as SKU_4,
    psd.PRODUCT_NAME as PRODUCT_NAME,
    psd.UPC as UPC,
    psd.PRODUCT_BRAND as SUB_BRAND,
    psd.MAJOR_CATEGORY + ' ' + psd.MAJOR_CATEGORY_DESC as MAJOR_CATEGORY,
    psd.MAJOR_CATEGORY as MAJOR_CATEGORY_CODE,
    psd.APPLICATION + ' ' + psd.APPLICATION_DESC as APPLICATION,
    psd.APPLICATION as APPLICATION_CODE,
    psd.CATEGORY +' ' + psd.CATEGORY_DESC as CATEGORY,
    psd.CATEGORY as CATEGORY_CODE,
    psd.SUB_CATEGORY + ' ' + psd.SUB_CATEGORY_DESC as SUB_CATEGORY,
    psd.SUB_CATEGORY as SUB_CATEGORY_CODE,
    psd.INVENTORY_HIER as 'INVENTORY_HIER',
    irtwd.QTY as EXPECTED_QTY,
    irtwd.QTY * irtwd.ORI_RETAIL_PRICE  as EXPECTED_VALUE,
    irtwd.ACTUAL_QTY as RECEIVED_QTY,
    irtwd.ACTUAL_QTY * irtwd.ORI_RETAIL_PRICE as RECEIVED_VALUE,
    0 as VARIANCE_QTY,
    irtwd.ACTUAL_QTY - irtwd.QTY as VARIANCE_VALUE,
    'N' as VARIANCE_PROMPT,
    pl.LOCATION_CODE as SHIPPING_STORE_CODE ,
    pl.LOCATION_DESC as SHIPPING_STORE_NAME,
    pl.CITY_TXT as SHIPPING_STORE_LOCATION,
    pst.STORE_TYPE_CODE as SHIPPING_STORE_TYPE,
    'WAREHOUSE' as RECEIVING_STORE_CODE ,
    'WAREHOUSE' as RECEIVING_STORE_NAME,
    'WAREHOUSE' as RECEIVING_STORE_LOCATION,
    'WAREHOUSE' as RECEIVING_STORE_TYPE,
    irtwh.CRE_DATET as CREATE_DATE,
    CONVERT(varchar(10), irtwh.CRE_DATET, 126) as TX_DT,
    --itoh.OUT_DT as SHIPPING_DATE,
    NULL as SHIPPING_DATE,
    ir.REASON_DESCRIPTION as REASON_CODE,
    --ir.POS_REASON_CODE as REASON_CODE,
    NULL as RECEIVE_DATE,
    irtwh.OVERALL_APPROVE_DT as APPROVAL_DATE,
    '' as RECEIVER_ID,
    '' as RECEIVER_NAME,
    irtwd.ORI_RETAIL_PRICE as SUGGESTED_RETAIL_PRICE,
    'RETURN TO WAREHOUSE' as ORDER_TYPE,
    CASE
        WHEN irtwh.OVERALL_APPROVAL_STATUS = 'APPROVED' and irtwh.STATUS = 'CONFIRM' then 'CLOSED'
        else 'IN PROGRESS'
    end as STATUS,
    NULL as STOCK_TRANSFER_DURATION_DAY,
    CASE
        WHEN RIGHT(pl.COUNTRY_ID_FK,3)='MAC' THEN 'MO'
        WHEN RIGHT(pl.COUNTRY_ID_FK,3)='HKG' THEN 'HK'
        ELSE LEFT(pl.COMPANY_CODE,2)
    END as ENTITY,
    psa.DEFAULT_UOM_CODE as UOM
from
    IT_RETURN_TO_WAREHOUSE_H irtwh
inner join IT_RETURN_TO_WAREHOUSE_D irtwd
    on irtwd.RTW_H_ID_FK = irtwh.RTW_H_ID
inner join PM_LOCATION pl
    on irtwh.COMPANY_CODE = pl.COMPANY_CODE
    and irtwh.LOCATION_CODE = pl.LOCATION_CODE
inner join PM_STORE_TYPE pst
    on pl.STORE_TYPE_ID_FK = pst.STORE_TYPE_ID
inner join PM_COMPANY pc
    on irtwh.COMPANY_CODE = pc.COMPANY_CODE
left join PV_SKU_DETAIL psd
    on irtwd.COMPANY_CODE = psd.COMPANY_CODE
    and irtwd.SKU_CODE = psd.SKU_10
LEFT join IM_REASON ir
    on ir.COMPANY_CODE = irtwh.COMPANY_CODE
    --and ir.SAP_REASON_CODE = irtwh.REASON
    and ir.POS_REASON_CODE = irtwh.REASON
LEFT join PM_SKU ps21 on irtwd.COMPANY_CODE = ps21.COMPANY_CODE and irtwd.SKU_CODE = ps21.SKU_CODE
LEFT join PM_SKU_ATTR psa on irtwd.COMPANY_CODE = psa.COMPANY_CODE and psa.SKU_ATTR_ID  = ps21.SKU_ATTR_ID_FK
where irtwh.OVERALL_APPROVAL_STATUS not in ( 'REJECTED' , 'NA');
