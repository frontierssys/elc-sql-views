CREATE   view [dbo].[PV_ONLINE_BP_RETURN_TXNS] as
SELECT DISTINCT pr.COMPANY_CODE ,
    pr.STORE_ID ,
    pr.CONSUMER_ID,
    pr.TRANSACTION_ID,
    psmid.ORIG_MEMO_NO,
    psm.TOTAL_NET_AMT as ORIG_TRANS_AMT,
    pvbm.RULE_DESC as ISSUE_RULE ,
    pvbm.POINT_MOVEMENT as ORIG_POINTS_ISSUED,
    pr.TOTAL_TRANSACTION_NET_SALES as RETURN_AMT,
    pvbm1.RULE_DESC as RETURN_RULE,
    pvbm1.POINT_MOVEMENT as RETURN_TXN_POINTS
FROM PV_R0016 pr
INNER JOIN PT_SALES_MEMO_ITEM_D psmid on psmid.SALES_MEMO_ITEM_H_ID_FK=pr.SALES_MEMO_ITEM_H_ID and psmid.ORIG_MEMO_NO is not null
INNER JOIN (
    SELECT ORDER_NO ,COMPANY_CODE ,Count(DISTINCT RULE_DESC) as RULES
    from PL_VIP_BP_MOVEMENT pvbm
    GROUP BY ORDER_NO,COMPANY_CODE
    HAVING Count(DISTINCT RULE_DESC)>1) a ON a.ORDER_NO=psmid.ORIG_MEMO_NO
LEFT JOIN PL_VIP_BP_MOVEMENT pvbm on pvbm.ORDER_NO =psmid.ORIG_MEMO_NO and pr.COMPANY_CODE =pvbm.COMPANY_CODE
LEFT JOIN PL_VIP_BP_MOVEMENT pvbm1 on pvbm1.ORDER_NO =pr.TRANSACTION_ID and pr.COMPANY_CODE =pvbm1.COMPANY_CODE and pvbm.RULE_DESC =pvbm1.RULE_DESC
INNER JOIN PT_SALES_MEMO psm ON psm.MEMO_NO =psmid.ORIG_MEMO_NO
where pr.CONSUMER_ID is not null and pr.POST_VOID ='N'
    and pr.TRANSACTION_DATE > GETDATE()-15 and pr.TOTAL_TRANSACTION_NET_SALES <>0 --and pvbm1.POINT_MOVEMENT <0
    --and pr.COMPANY_CODE ='HKCL'
    and pr.STORE_TYPE_CODE ='ONLI'
    --and pr.TRANSACTION_ID IN ('HKEL0029012I21000492','HKEL0029022I21001088')
