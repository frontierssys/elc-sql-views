CREATE   VIEW [dbo].[PV_R0038_SERVICE_PACKAGE] AS
SELECT DISTINCT pvsih.COMPANY_CODE ,
    pl.LOCATION_CODE as LOCATION_CODE,
    pvsih.COMPANY_CODE as DIVISION,
    pvsih.PACKAGE_TYPE as ORDER_TYPE,
    pst.STORE_TYPE_CODE as STORE_TYPE_NAME,
    pl.CITY_TXT as STORE_LOCATION,
    pl.LOCATION_CODE as STORE_ID,
    pl.LOCATION_NAME as STORE_NAME,
    'Service Package' as LIABILITY_TYPE,
    pvsih.VIP_SVC_ITEM_H_ID as LIABILITY_ID,
    'NA' as LIABILITY_DESCRIPTION,
    'Service Package SALES' as TRAN_TYPE,
    CASE
        when pvsi.SVC_ITEM_STATUS is not null then 'OPEN'
        else 'CLOSE'
    end as STATUS,
    pvsih.SALES_MEMO_NO as TRANSACTION_NUMBER,
    COALESCE (CAST(psm.TX_DT as date),CAST(pvsih.CRE_DATET as date)) as TX_DATE,
    COALESCE (CAST(psm.TX_DT as time),CAST(pvsih.CRE_DATET as time)) as TRANSACTION_TIME,
    ps22.STAFF_CODE as BA_ID,
    ps22.FIRST_NAME + ' ' + ps22.LAST_NAME as BA_NAME,
    pv.VIP_NO as CUSTOMER_ID,
    pc.FIRSTNAME + ' ' + pc.SURNAME as CUSTOMER_NAME,
    pvsih.SKU_CODE as SKU10,
    LEFT(pvsih.SKU_CODE,6) as SKU6 ,
    LEFT(pvsih.SKU_CODE,4) as SKU4 ,
    pvsih.SVC_PKG_DESC as PRODUCT_DESCRIPTION,
    1 as QUANTITY,
    pvsih.SELLING_PRICE as SALES_AMOUNT,
    case
        when pvsi.SVC_ITEM_STATUS IN('PENDING','EXPIRED') then SUM(pvsi.PRICE)
        else 0
    end as REMAINING_BALANCE,
    CAST (pvsih.EFFECTIVE_DATE as date) as ORIGINAL_PURCHASE_DATE,
    DATEDIFF(day,CAST (pvsih.EFFECTIVE_DATE as date),GETDATE()) as DAYS_SINCE_POURCHASE_DATE,
    CAST (pvsih.EXPIRY_DT as date) as EXPIRATION_DATE,
    CASE
        when DATEDIFF(day, GETDATE(), CAST(pvsih.EXPIRY_DT as date)) < 0 then 'Y'
        ELSE 'N'
    END as EXPIRED
from PM_VIP_SVC_ITEM_H pvsih
LEFT JOIN PM_VIP_SVC_ITEM pvsi  ON pvsih.VIP_SVC_ITEM_H_ID=pvsi.VIP_SVC_ITEM_H_ID_FK and pvsi.SVC_ITEM_STATUS IN('PENDING','EXPIRED')
LEFT JOIN PT_SALES_MEMO psm ON psm.MEMO_NO =pvsih.SALES_MEMO_NO and psm.COMPANY_CODE =pvsih.COMPANY_CODE
LEFT JOIN PM_LOCATION pl on pl.LOCATION_ID = psm.LOCATION_ID_FK
LEFT JOIN PM_STORE_TYPE pst on 	pst.STORE_TYPE_ID = pl.STORE_TYPE_ID_FK
LEFT JOIN PM_VIP pv on 	pv.COMPANY_CODE = pvsih.COMPANY_CODE and pv.VIP_NO = pvsih.VIP_NO
LEFT JOIN PM_CUSTOMER pc on pv.CUSTOMER_ID_FK = pc.CUSTOMER_ID
LEFT JOIN dbo.PM_STAFF ps22 on ps22.COMPANY_CODE = psm.COMPANY_CODE and ps22.STAFF_CODE = psm.CASHIER_CODE
WHERE 1=1 --and pvsih.VIP_SVC_ITEM_H_ID='HKBBHQ000000000033359253'
GROUP BY pvsih.COMPANY_CODE, pl.LOCATION_CODE, pst.STORE_TYPE_CODE, pl.CITY_TXT, pl.LOCATION_CODE, pl.LOCATION_NAME,
    pvsih.SALES_MEMO_NO, pvsih.SKU_CODE, psm.TX_DT, ps22.STAFF_CODE, pc.FIRSTNAME, pc.SURNAME, ps22.FIRST_NAME, ps22.LAST_NAME, pv.VIP_NO,
    pvsih.SVC_PKG_DESC, pvsih.EXPIRY_DT,pvsih.PACKAGE_TYPE,pvsih.VIP_SVC_ITEM_H_ID ,pvsih.EFFECTIVE_DATE,pvsi.SVC_ITEM_STATUS,pvsih.SELLING_PRICE,pvsih.CRE_DATET
UNION
SELECT pvsih.COMPANY_CODE ,
    pl.LOCATION_CODE as LOCATION_CODE,
    pvsih.COMPANY_CODE as DIVISION,
    pvsih.PACKAGE_TYPE as ORDER_TYPE,
    pst.STORE_TYPE_CODE as STORE_TYPE_NAME,
    pl.CITY_TXT as STORE_LOCATION,
    pl.LOCATION_CODE as STORE_ID,
    pl.LOCATION_NAME as STORE_NAME,
    'Service Package' as LIABILITY_TYPE,
    pvsih.VIP_SVC_ITEM_H_ID as LIABILITY_ID,
    'NA' as LIABILITY_DESCRIPTION,
    'Service Package ' + pvsi.SVC_ITEM_STATUS as TRAN_TYPE,
    case
        when SUM(
            case
                when pvsi.SVC_ITEM_STATUS IN ('PENDING','EXPIRED') then pvsi.PRICE
                else 0
            end
        ) > 0 then 'OPEN'
        else 'CLOSE'
    end as STATUS,
    pvsi.REDEEM_MEMO_NO as TRANSACTION_NUMBER,
    COALESCE (CAST(psm.TX_DT as date),CAST(pvsih.CRE_DATET as date)) as TX_DATE,
    COALESCE (CAST(psm.TX_DT as time),CAST(pvsih.CRE_DATET as time)) as TRANSACTION_TIME,
    ps22.STAFF_CODE as BA_ID,
    ps22.FIRST_NAME + ' ' + ps22.LAST_NAME as BA_NAME,
    pv.VIP_NO as CUSTOMER_ID,
    pc.FIRSTNAME + ' ' + pc.SURNAME as CUSTOMER_NAME,
    pvsi.SKU_CODE as SKU10,
    LEFT(pvsi.SKU_CODE,6) as SKU6 ,
    LEFT(pvsi.SKU_CODE,4) as SKU4 ,
    pvsi.SVC_ITEM_DESC as PRODUCT_DESCRIPTION,
    count(seq) as QUANTITY,
    SUM(pvsi.PRICE)*-1 as SALES_AMOUNT,
    /*SUM(
        case when pvsi.SVC_ITEM_STATUS IN('PENDING','EXPIRED') then pvsi.PRICE else 0 end
        ) as REMAINING_BALANCE,*/
    case
        when pvsi.SVC_ITEM_STATUS IN('PENDING','EXPIRED') then pvsi.PRICE*-1
        else 0
    end as REMAINING_BALANCE,
    CAST (pvsih.EFFECTIVE_DATE as date) as ORIGINAL_PURCHASE_DATE,
    DATEDIFF(day,CAST (pvsih.EFFECTIVE_DATE as date),GETDATE()) as DAYS_SINCE_POURCHASE_DATE,
    CAST (pvsih.EXPIRY_DT as date) as EXPIRATION_DATE,
    CASE
        when DATEDIFF(day, GETDATE(), CAST(pvsih.EXPIRY_DT as date)) < 0 then 'Y'
        ELSE 'N'
    END as EXPIRED
from PM_VIP_SVC_ITEM pvsi
INNER JOIN PM_VIP_SVC_ITEM_H pvsih ON pvsih.VIP_SVC_ITEM_H_ID=pvsi.VIP_SVC_ITEM_H_ID_FK
LEFT JOIN PT_SALES_MEMO psm ON psm.MEMO_NO =pvsi.REDEEM_MEMO_NO
LEFT JOIN PM_LOCATION pl on pl.LOCATION_ID = psm.LOCATION_ID_FK
LEFT JOIN PM_STORE_TYPE pst on 	pst.STORE_TYPE_ID = pl.STORE_TYPE_ID_FK
LEFT JOIN PM_VIP pv on 	pv.COMPANY_CODE = pvsih.COMPANY_CODE and pv.VIP_NO = pvsih.VIP_NO
LEFT JOIN PM_CUSTOMER pc on pv.CUSTOMER_ID_FK = pc.CUSTOMER_ID
LEFT JOIN dbo.PM_STAFF ps22 on ps22.COMPANY_CODE = psm.COMPANY_CODE and ps22.STAFF_CODE = psm.CASHIER_CODE
WHERE 1=1 and pvsi.REDEEM_MEMO_NO is not null --and pvsih.VIP_SVC_ITEM_H_ID='HKBBHQ000000000033359253'
GROUP BY pvsih.COMPANY_CODE, pl.LOCATION_CODE, pst.STORE_TYPE_CODE, pl.CITY_TXT, pl.LOCATION_CODE, pl.LOCATION_NAME,
    pvsi.REDEEM_MEMO_NO, pvsi.SKU_CODE, psm.TX_DT, ps22.STAFF_CODE, pc.FIRSTNAME, pc.SURNAME, ps22.FIRST_NAME, ps22.LAST_NAME, pv.VIP_NO,
    pvsi.SVC_ITEM_DESC, pvsi.PRICE, pvsih.EXPIRY_DT,pvsih.PACKAGE_TYPE,pvsih.VIP_SVC_ITEM_H_ID ,pvsih.CRE_DATET,pvsi.SVC_ITEM_STATUS,pvsih.EFFECTIVE_DATE
