--Script to Find BALANCE, SOH, IN_TRANSIT, SELL_THROUGH QTY
CREATE   VIEW [dbo].[PV_ACTUAL_SELL_THROUGH_RAW_DATA_MOVEMENT_BY_DAY] AS
SELECT
    timbd.COMPANY_CODE ,
    timbd.LOCATION_CODE,
    'SOH' as MOVEMENT_TYPE,
    timbd.SKU as SKU_10,
    timbd.MOVEMENT_DATE ,
    timbd.BALANCE,
    sum(timbd.MOVEMENT_QTY) as MOVEMENT_QTY
from
    PV_INVENTORY_MOVEMENT_BY_DAY_V2 timbd
inner join
    (
        select
            a.COMPANY_CODE  , a.LOCATION_CODE, a.BALANCE_TYPE , a.SKU, max(a.OPEN_BALANCE_DT) MAX_BALANCE_DT
        from
            PV_INVENTORY_MOVEMENT_BY_DAY_V2 a
        where a.OPEN_BALANCE_DT <= getdate()
        group by
            a.COMPANY_CODE  , a.LOCATION_CODE, a.BALANCE_TYPE , a.SKU
    ) inv
    on timbd.COMPANY_CODE = inv.COMPANY_CODE
    and timbd.LOCATION_CODE = inv.LOCATION_CODE
    and timbd.BALANCE_TYPE = inv.BALANCE_TYPE
    and timbd.SKU = inv.SKU
    and timbd.OPEN_BALANCE_DT = inv.MAX_BALANCE_DT
where 1 =1
    and timbd.BALANCE_TYPE = 'ONHAND'
    --and timbd.MOVEMENT_DATE <= '2021-06-01'
    --and timbd.sku='5RTX400000'
    --and timbd.LOCATION_CODE ='HKBB0003'
group by
    timbd.COMPANY_CODE ,
    timbd.LOCATION_CODE,
    timbd.BALANCE_TYPE ,
    timbd.SKU,
    timbd.BALANCE ,
    timbd.MOVEMENT_DATE
UNION ALL
SELECT COMPANY_CODE , LOCATION_ID as LOCATION_CODE, 'SELL-THROUGH' as MOVEMENT_TYPE ,SKU as SKU_10 ,MOVEMENT_DATE, 0 as BALANCE,SUM(MOVEMENT_QTY) as MOVEMENT_QTY
FROM PL_INVENTORY_LOG pil
where ORDER_TYPE='SALES' and MOVEMENT_TYPE NOT IN ('RETURN')
--and MOVEMENT_DATE <= '2021-06-01' and sku='E0KK020000' and LOCATION_ID ='HKBB0003'
GROUP BY COMPANY_CODE , LOCATION_ID,SKU ,MOVEMENT_DATE
UNION ALL
SELECT iah.COMPANY_CODE , iah.SAP_CUSTOMER_CODE as LOCATION_CODE,'IN-TRANSIT'  as MOVEMENT_TYPE, iad.PRODUCT_CODE as SKU_10,CAST(iah.CRE_DATET as Date) as MOVEMENT_DATE,0 as BALANCE,
    SUM(iad.TOTAL_QTY) as MOVEMENT_QTY
FROM IT_ASN_H iah
INNER JOIN IT_ASN_D iad on iad.ASN_H_ID_FK =iah.ASN_H_ID
WHERE iah.RECEIVE_STATUS NOT IN ('RECEIVED') and iad.TARGET_BALANCE ='ONHAND'
GROUP BY iah.COMPANY_CODE ,iah.SAP_CUSTOMER_CODE , iad.PRODUCT_CODE ,CAST(iah.CRE_DATET as Date)
