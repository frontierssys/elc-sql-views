CREATE   VIEW PV_R0084 as
SELECT DISTINCT pvgcl.COMPANY_CODE ,
    pv.VIP_NO ,
    dt.TX_DATE,
    dt.MEMO_NO,
    dt.POS_MEMO_NO,
    pm.LOCATION_CODE,
    dt.TOTAL_NET_AMT,
    dt.CRE_DATET as TRANS_CRE_DATE,
    pvg2.VIP_GRADE_DESCRIPTION as CURRENT_TIER,
    pvgcl.REMARKS as LOYALTY_STATUS,
    pvgcl.CHANGE_DT as TIER_CHANGE_DATE,
    pvt.EXPIRY_DAY as MEM_END_DATE,
    ISNULL(pvps.LIFETIME_SPEND,0) as LIFETIME_SPEND ,
    ISNULL(pvpb.POINTS,0) as BALANCE,
    pvt.EXPIRY_DAY as PT_EXP_DATE,
    pvg.VIP_GRADE_DESCRIPTION as PREVIOUS_TIER
FROM PL_VIP_GRADE_CHG_LOG pvgcl
INNER JOIN PM_VIP pv on pv.VIP_NO = pvgcl.VIP_NO  and pv.COMPANY_CODE =pvgcl.COMPANY_CODE
INNER JOIN (
    SELECT COMPANY_CODE ,VIP_NO ,CRE_DATET,TX_DATE,MEMO_NO,POS_MEMO_NO ,LOCATION_ID_FK,TOTAL_NET_AMT
    from PT_SALES_MEMO psm
    WHERE DATEDIFF(day,TX_DATE ,CRE_DATET) >0 and MEMO_NO is NOT NULL and VIP_NO is NOT NULL) dt ON dt.COMPANY_CODE=pvgcl.COMPANY_CODE and dt.VIP_NO=pv.VIP_NO
LEFT JOIN PM_VIP_TYPE pvt on pvt.VIP_TYPE_ID =pv.VIP_TYPE_ID_FK and pvt.COMPANY_CODE =pv.COMPANY_CODE
LEFT JOIN PM_VIP_GRADE pvg ON pvg.VIP_GRADE_CODE =pvgcl.VIP_GRADE_FROM and pvg.COMPANY_CODE =pvgcl.COMPANY_CODE
LEFT JOIN PM_VIP_GRADE pvg2 ON pvg2.VIP_GRADE_CODE =pvgcl.VIP_GRADE_TO and pvg2.COMPANY_CODE =pvgcl.COMPANY_CODE
LEFT JOIN PMV_VIP_P12_SPENDING pvps ON pvps.VIP_ID = pv.VIP_ID
LEFT JOIN (
    SELECT pvcp.COMPANY_CODE ,pvcp.VIP_NO,SUM(pvcp.POINTS) as POINTS
    from PV_VIP_CURRENT_POINTS pvcp
    Group by pvcp.COMPANY_CODE,pvcp.VIP_NO ) pvpb
    on pvpb.VIP_NO = pv.VIP_NO and pvpb.COMPANY_CODE=pv.COMPANY_CODE
LEFT JOIN PM_LOCATION pm ON pm.LOCATION_ID = dt.LOCATION_ID_FK and pm.COMPANY_CODE = dt.COMPANY_CODE
WHERE --dt.TX_DATE<pvgcl.CHANGE_DT  and dt.CRE_DATET>pvgcl.CHANGE_DT and
    dt.LOCATION_ID_FK like 'TW%ONLI' and DATEDIFF(day,dt.TX_DATE ,pvgcl.CHANGE_DT) >0 and DATEDIFF(day,pvgcl.CHANGE_DT ,dt.CRE_DATET) >0;
