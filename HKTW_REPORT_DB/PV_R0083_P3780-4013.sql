-- dbo.[PV_R0083_P3780-4013] source

CREATE   view [PV_R0083_P3780-4013] AS
SELECT psm.COMPANY_CODE ,
    pcn.CAMPAIGN_CODE ,
    pcn.NAME  as DESCRIPTION,
    psm.STORE_ID ,
    --psm.STORE_LOCATION as LOCATION_DESC,
    psm.STORE_NAME as LOCATION_DESC,
    psm.CONSUMER_ID as VIP_NO,
    psm.TRANSACTION_ID as MEMO_NO,
    psm.MATERIAL_CODE_10 as PRODUCT_CODE,
    psm.PRODUCT_NAME as PRODUCT_DESC,
    psm.COMMISSION_EMPLOYEE_ID ,
    sum(psm.QUANTITY) as QTY,
    sum(psm.NET_SALES) as UNIT_NET_SALES,
    psm.TOTAL_TRANSACTION_NET_SALES as TOTAL_NET_AMT,
    psm.TRANSACTION_DATE as TX_DATE ,
    psm.VIRTUAL_SET_ID as VIRTUAL_SET_CODE
FROM PT_SALES_MEMO_CAMPAIGN psmc
INNER JOIN PV_R0016 psm on psmc.SALES_MEMO_ID_FK = psm.SALES_MEMO_ID and psm.COMPANY_CODE =psmc.COMPANY_CODE
Left JOIN PM_CAMPAIGN pcn on pcn.COMPANY_CODE = psmc.COMPANY_CODE and psmc.CAMPAIGN_CODE = pcn.CAMPAIGN_CODE
/*where psm.COMPANY_CODE ='TWJM' and psm.TRANSACTION_DATE >='2021-02-24'
and pcn.CAMPAIGN_CODE in ('MDPRE', 'MD_2022')*/
group by psm.COMPANY_CODE ,
    pcn.CAMPAIGN_CODE ,
    pcn.NAME ,
    psm.STORE_ID ,
    psm.STORE_NAME,
    psm.CONSUMER_ID ,
    psm.TRANSACTION_ID ,
    psm.MATERIAL_CODE_10 ,
    psm.PRODUCT_NAME,
    psm.COMMISSION_EMPLOYEE_ID,
    psm.TOTAL_TRANSACTION_NET_SALES,
    psm.TRANSACTION_DATE,
    psm.VIRTUAL_SET_ID;
