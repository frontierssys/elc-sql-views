-- dbo.PV_POINT_TYPE_MAPPING source

CREATE  VIEW PV_POINT_TYPE_MAPPING AS
SELECT DISTINCT pvbm.COMPANY_CODE,pvbm.ORDER_TYPE ,
    pvbm.MOVEMENT_TYPE,
    pvbm.LOYALTY_POINT_TYPE,
    CASE
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-ADJUSTMENT-ADJUSTMENT' THEN 'ADJUSTMENT_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='ADJUSTMENT-EXPIRE_DATE_RESET-BASIC' THEN 'ADJUSTMENT_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='ADJUSTMENT-EXPIRE_DATE_RESET-ADJUSTMENT' THEN 'ADJUSTMENT_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='ADJUSTMENT-ADJUSTMENT-ADJUSTMENT' THEN 'ADJUSTMENT_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-RETURN-NEW_MEMBER' THEN 'BASIC_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-SALES-BASIC' THEN 'BASIC_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-SALES-REENROLL_MEMBER' THEN 'BASIC_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-RETURN-BASIC' THEN 'BASIC_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-SALES-REPLENISHMENT' THEN 'BASIC_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-SALES-NEW_MEMBER' THEN 'BASIC_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='REDEEM-GIFT-GIFT' THEN 'REDEEM_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-VOID-BASIC' THEN 'BASIC_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-VOID-OTHERS' THEN 'BONUS_POINT'
        WHEN CONCAT(pvbm.ORDER_TYPE ,'-', pvbm.MOVEMENT_TYPE,'-', pvbm.LOYALTY_POINT_TYPE)='SALES-VOID-VOID' THEN 'BASIC_POINT'
        ELSE 'BONUS_POINT'
    END as POINT_TYPE
from PL_VIP_BP_MOVEMENT pvbm;
