CREATE

VIEW "PV_PARENT_CHILD_SKU" AS
SELECT
    ps.COMPANY_CODE,
    ps.SKU_CODE as PARENT_SKU,
    ps.SKU_DESC as PARENT_PRODUCT_NAME,
    isnull (pbid.SKU_CODE, ps.SKU_CODE) as CHILD_SKU
FROM
    PM_SKU ps
LEFT JOIN PM_BOM_ITEM_H pbih ON pbih.SKU_CODE = ps.sku_code
    and ps.COMPANY_CODE = pbih.COMPANY_CODE
LEFT JOIN PM_BOM_ITEM_D pbid ON pbih.BOM_ITEM_H_ID = pbid.BOM_ITEM_H_ID_FK;
