CREATE   view PV_R0027A  as
SELECT A.COMPANY_CODE, A.CONSUMER_ID, BIRTH_M,LAST_NAME, FIRST_NAME, TEL1, TEL2, EMAIL, PURCHASE_STORE_ID,
    PURCHASE_STORE_NAME,  BIRTH_D, CREATION_STORE_ID as REG_STORE, CREATION_STORE_NAME as REG_STORE_NAME, CREATION_DATE as REG_STORE_DATE, FIRST_PURCHASE_STORE_ID,
    FIRST_PURCHASE_STORE_NAME, FIRST_PURCHASE_DATE, LAST_PURCHASE_STORE_ID, LAST_PURCHASE_STORE_NAME, LAST_PURCHASE_DATE,
    MOST_FREQUENT_STORE_ID, MOST_FREQUENT_STORE_NAME, LAST_LOYALTY_REDEMPTION, LIFETIME_SPEND, LIFETIME_TRANSACTION,
    SUM(SPEND_WITHIN_RANGE) SWR, SUM(LOYALTY_POINT_GAINED_WITHIN_RANGE) LPGWR, SUM(LOYALTY_POINTS_REDEEMED_WITHIN_RANGE) LPRWR,
    SUM(TRANSACTION_WITHIN_RANGE) TWR, FY_YTD_SPEND, FY_YTD_TRANS, ROLLING_12_SPEND, ROLLING_12_TRANS, LOYALTY_EXPIRE_DATE,
    CURRENT_LOYALTY_POINTS, REDEEMED_POINTS, OPT_IN_SMS, OPT_IN_PHONE, OPT_IN_EMAIL, OPT_IN_DIRECT_MAIL, AGE_GROUP,
    pvgcl.REMARKS as LOYALTY_STATUS , pvg.VIP_GRADE_DESCRIPTION  as TIER_FROM , pvg2.VIP_GRADE_DESCRIPTION  as TIER_TO, pvgcl.CHANGE_DT as TIER_CHANGE_DATE,
    pvt.START_DATE as MEM_START_DT, pvt.EXPIRY_DAY as MEM_END_DATE
FROM PV_R0027 A
INNER JOIN PL_VIP_GRADE_CHG_LOG pvgcl on pvgcl.VIP_NO =A.CONSUMER_ID  and A.COMPANY_CODE =pvgcl.COMPANY_CODE
LEFT JOIN PM_VIP_GRADE pvg ON pvg.VIP_GRADE_CODE =pvgcl.VIP_GRADE_FROM and pvg.COMPANY_CODE =pvgcl.COMPANY_CODE
LEFT JOIN PM_VIP_GRADE pvg2 ON pvg2.VIP_GRADE_CODE =pvgcl.VIP_GRADE_TO and pvg2.COMPANY_CODE =pvgcl.COMPANY_CODE
LEFT JOIN PM_VIP pv on pv.VIP_NO = A.CONSUMER_ID and pv.COMPANY_CODE =A.COMPANY_CODE
LEFT JOIN PM_VIP_TYPE pvt on pvt.VIP_TYPE_ID =pv.VIP_TYPE_ID_FK and pvt.COMPANY_CODE =pv.COMPANY_CODE
WHERE 1 = 1 --AND  A.COMPANY_CODE = 'TWCM'  --AND A.CONSUMER_ID IN ('53000000212','55000000109')
GROUP BY A.COMPANY_CODE,CONSUMER_ID, SALUTATION, LAST_NAME, FIRST_NAME, TEL1, TEL2, EMAIL, PURCHASE_STORE_ID,
    PURCHASE_STORE_NAME, BIRTH_M, BIRTH_D, CREATION_STORE_ID, CREATION_STORE_NAME, CREATION_DATE,
    FIRST_PURCHASE_STORE_ID, FIRST_PURCHASE_STORE_NAME, FIRST_PURCHASE_DATE, LAST_PURCHASE_STORE_ID,
    LAST_PURCHASE_STORE_NAME, LAST_PURCHASE_DATE, MOST_FREQUENT_STORE_ID, MOST_FREQUENT_STORE_NAME,
    LAST_LOYALTY_REDEMPTION, LIFETIME_SPEND, LIFETIME_TRANSACTION, FY_YTD_SPEND, FY_YTD_TRANS, ROLLING_12_SPEND,
    ROLLING_12_TRANS, LOYALTY_EXPIRE_DATE, CURRENT_LOYALTY_POINTS, REDEEMED_POINTS, OPT_IN_SMS, OPT_IN_PHONE,
    OPT_IN_EMAIL, OPT_IN_DIRECT_MAIL, AGE_GROUP,pvgcl.REMARKS , pvg.VIP_GRADE_DESCRIPTION , pvg2.VIP_GRADE_DESCRIPTION, pvgcl.CHANGE_DT,
    pvt.START_DATE,pvt.EXPIRY_DAY;
