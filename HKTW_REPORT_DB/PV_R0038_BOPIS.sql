CREATE VIEW [dbo].[PV_R0038_BOPIS] AS
SELECT psmbi.COMPANY_CODE ,
    pl.LOCATION_CODE as LOCATION_CODE,
    psmbi.COMPANY_CODE as DIVISION,
    'BOPIS Order' as ORDER_TYPE,
    pst.STORE_TYPE_CODE as STORE_TYPE_NAME,
    pl.CITY_TXT as STORE_LOCATION,
    pl.LOCATION_CODE as STORE_ID,
    pl.LOCATION_NAME as STORE_NAME,
    'BOPIS Order' as LIABILITY_TYPE,
    psm.POS_MEMO_NO as LIABILITY_ID,
    ISNULL(psmbi.REASON_CODE,'NA') as LIABILITY_DESCRIPTION,
    CASE
        when psmbi.BOPIS_ORDER_STATUS IN ('COLLECTED','CANCELED') then 'BOPIS ORDER ORIGINAL'
        else psmbi.BOPIS_ORDER_STATUS
    END as TRAN_TYPE,
    CASE
        when psmbi.BOPIS_ORDER_STATUS IN ('PENDING_PICK','SLA_EXCEEDED','PENDING_COLLECT') then 'OPEN'
        else 'CLOSE'
    end as STATUS,
    psm.MEMO_NO as TRANSACTION_NUMBER,
    CASE
        WHEN psmbi.BOPIS_ORDER_STATUS IN ('ABANDONED','REJECTED') then CAST(psmbi.STATUS_CHG_DATE as date)
        ELSE CAST(psm.TX_DT as date)
    END as TX_DATE,
    CASE
        WHEN psmbi.BOPIS_ORDER_STATUS IN ('ABANDONED','REJECTED') then CAST(psmbi.STATUS_CHG_DATE as time)
        ELSE CAST(psm.TX_DT as time)
    END as TRANSACTION_TIME,
    ps22.USER_CODE as BA_ID,
    ps22.NAME as BA_NAME,
    psmbi.ONLINE_CONSUMER_ID as CUSTOMER_ID,
    psmbi.BOPIS_FIRST_NAME + ' ' + psmbi.BOPIS_LAST_NAME as CUSTOMER_NAME,
    'NA' as SKU10,
    'NA' as SKU6 ,
    'NA' as SKU4 ,
    'NA' as PRODUCT_DESCRIPTION,
    0 as QUANTITY,
    case
        when psmbi.BOPIS_ORDER_STATUS NOT IN('PENDING_PICK','SLA_EXCEEDED','PENDING_COLLECT','COLLECTED','CANCELED') then psm.TOTAL_NET_AMT*-1
        else psm.TOTAL_NET_AMT
    end as SALES_AMOUNT,
    case
        when psmbi.BOPIS_ORDER_STATUS IN('PENDING_PICK','SLA_EXCEEDED','PENDING_COLLECT') then psm.TOTAL_NET_AMT
        else 0
    end as REMAINING_BALANCE,
    CAST(psm.TX_DT as date) as ORIGINAL_PURCHASE_DATE,
    DATEDIFF(day,CAST (psm.TX_DT as date),GETDATE()) as DAYS_SINCE_POURCHASE_DATE,
    CAST (psm.TX_DT+365 as date) as EXPIRATION_DATE,
    CASE
        when DATEDIFF(day, GETDATE(), CAST (psm.TX_DT+365 as date)) < 0 then 'Y'
        ELSE 'N'
    END as EXPIRED
from PT_SALES_MEMO_BOPIS_INFO psmbi
INNER JOIN PT_SALES_MEMO psm ON psm.SALES_MEMO_BOPIS_INFO_ID_FK =psmbi.SALES_MEMO_BOPIS_INFO_ID
LEFT JOIN PM_LOCATION pl on pl.LOCATION_ID = psm.LOCATION_ID_FK
LEFT JOIN PM_STORE_TYPE pst on 	pst.STORE_TYPE_ID = pl.STORE_TYPE_ID_FK
LEFT JOIN dbo.PM_USER ps22 on ps22.COMPANY_CODE = psm.COMPANY_CODE and ps22.USER_CODE = psm.CASHIER_CODE
WHERE 1=1 --and pl.LOCATION_CODE='HKEL0026'--and psm.POS_MEMO_NO IN ('1006407415','1006416605')
GROUP BY psmbi.COMPANY_CODE, pl.LOCATION_CODE, pst.STORE_TYPE_CODE, pl.CITY_TXT, pl.LOCATION_CODE, pl.LOCATION_NAME,
    psm.POS_MEMO_NO, ISNULL(psmbi.REASON_CODE,'NA'), psm.TX_DT, ps22.USER_CODE, psmbi.BOPIS_FIRST_NAME, psmbi.BOPIS_LAST_NAME, ps22.NAME,
    psmbi.ONLINE_CONSUMER_ID,psmbi.BOPIS_ORDER_STATUS,psm.MEMO_NO,psm.TOTAL_NET_AMT,psmbi.STATUS_CHG_DATE
UNION
SELECT psmbi.COMPANY_CODE ,
    pl.LOCATION_CODE as LOCATION_CODE,
    psmbi.COMPANY_CODE as DIVISION,
    'BOPIS Order' as ORDER_TYPE,
    pst.STORE_TYPE_CODE as STORE_TYPE_NAME,
    pl.CITY_TXT as STORE_LOCATION,
    pl.LOCATION_CODE as STORE_ID,
    pl.LOCATION_NAME as STORE_NAME,
    'BOPIS Order' as LIABILITY_TYPE,
    psm.POS_MEMO_NO as LIABILITY_ID,
    ISNULL(psmbi.REASON_CODE,'NA') as LIABILITY_DESCRIPTION,
    psmbi.BOPIS_ORDER_STATUS as TRAN_TYPE,
    'CLOSE' as STATUS,
    psmbi.REDEEM_MEMO_NO as TRANSACTION_NUMBER,
    CAST(psm2.TX_DT as date) as TX_DATE,
    CAST(psm2.TX_DT as time) as TRANSACTION_TIME,
    ps22.USER_CODE as BA_ID,
    ps22.NAME as BA_NAME,
    psmbi.ONLINE_CONSUMER_ID as CUSTOMER_ID,
    psmbi.BOPIS_FIRST_NAME + ' ' + psmbi.BOPIS_LAST_NAME as CUSTOMER_NAME,
    'NA' as SKU10,
    'NA' as SKU6 ,
    'NA' as SKU4 ,
    'NA' as PRODUCT_DESCRIPTION,
    0 as QUANTITY,
    (psm.TOTAL_NET_AMT)*-1 as SALES_AMOUNT,
    0 as REMAINING_BALANCE,
    CAST(psm.TX_DT as date) as ORIGINAL_PURCHASE_DATE,
    DATEDIFF(day,CAST (psm.TX_DT as date),GETDATE()) as DAYS_SINCE_POURCHASE_DATE,
    CAST (GETDATE()+365 as date) as EXPIRATION_DATE,
    CASE
        when DATEDIFF(day, GETDATE(), CAST (GETDATE()+365 as date)) < 0 then 'Y'
        ELSE 'N'
    END as EXPIRED
from PT_SALES_MEMO_BOPIS_INFO psmbi
INNER JOIN PT_SALES_MEMO psm ON psm.SALES_MEMO_BOPIS_INFO_ID_FK =psmbi.SALES_MEMO_BOPIS_INFO_ID
INNER JOIN PT_SALES_MEMO psm2 ON psm2.MEMO_NO =psmbi.REDEEM_MEMO_NO
LEFT JOIN PM_LOCATION pl on pl.LOCATION_ID = psm.LOCATION_ID_FK
LEFT JOIN PM_STORE_TYPE pst on 	pst.STORE_TYPE_ID = pl.STORE_TYPE_ID_FK
LEFT JOIN dbo.PM_USER ps22 on ps22.COMPANY_CODE = psm.COMPANY_CODE and ps22.USER_CODE = psm2.CASHIER_CODE
WHERE 1=1 and psmbi.BOPIS_ORDER_STATUS IN ('COLLECTED','CANCELED') --and pl.LOCATION_CODE='HKEL0026'--and psm.POS_MEMO_NO IN ('1006407415','1006416605')
GROUP BY psmbi.COMPANY_CODE, pl.LOCATION_CODE, pst.STORE_TYPE_CODE, pl.CITY_TXT, pl.LOCATION_CODE, pl.LOCATION_NAME,
    psm.POS_MEMO_NO, ISNULL(psmbi.REASON_CODE,'NA'), psm2.TX_DT, ps22.USER_CODE, psmbi.BOPIS_FIRST_NAME, psmbi.BOPIS_LAST_NAME, ps22.NAME,
    psmbi.ONLINE_CONSUMER_ID,psmbi.BOPIS_ORDER_STATUS,psmbi.REDEEM_MEMO_NO,psm.TX_DT,psm.TOTAL_NET_AMT;
