CREATE VIEW PV_R0063 AS
SELECT psd.COMPANY_CODE as COMPANY_CODE ,
    psd.SKU_10  as PARENT_SKU,
    psd.PRODUCT_NAME  as PARENT_SKU_DESC,
    pbid.SKU_CODE  as BOM_SKU,
    ps1.SKU_DESC  as BOM_SKU_DESC
FROM PV_SKU_DETAIL psd
LEFT JOIN PM_BOM_ITEM_H pbih  on  pbih.COMPANY_CODE =psd.COMPANY_CODE  and pbih.SKU_CODE =psd.SKU_10
LEFT JOIN PM_BOM_ITEM_D pbid on pbih.BOM_ITEM_H_ID =pbid.BOM_ITEM_H_ID_FK
LEFT JOIN PM_SKU ps1 on ps1.SKU_CODE =pbid.SKU_CODE  and ps1.COMPANY_CODE =pbid.COMPANY_CODE
WHERE psd.SKU_10 NOT IN (
    select SKU_CODE
    from PM_BOM_ITEM_D);
